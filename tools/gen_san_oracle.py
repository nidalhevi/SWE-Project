#!/usr/bin/env python3
"""Regenerate tests/san_oracle.inc: every legal move of a few positions with its python-chess SAN."""
import chess

FENS = [
    "rnbqkbnr/pppppppp/8/8/8/8/PPPPPPPP/RNBQKBNR w KQkq - 0 1",
    "r3k2r/p1ppqpb1/bn2pnp1/3PN3/1p2P3/2N2Q1p/PPPBBPPP/R3K2R w KQkq - 0 1",
    "r3k2r/Pppp1ppp/1b3nbN/nP6/BBP1P3/q4N2/Pp1P2PP/R2Q1RK1 w kq - 0 1",
    "rnbq1k1r/pp1Pbppp/2p5/8/2B5/8/PPP1NnPP/RNBQK2R w KQ - 1 8",
    "R6R/3Q4/1Q4Q1/4Q3/2Q4Q/Q4Q2/pp1Q4/kBNN1KB1 w - - 0 1",
    "4k3/8/8/8/8/8/8/R3K2R w KQ - 0 1",
    "8/8/8/KPp4r/8/8/8/4k3 w - c6 0 1",
    "rnbqkbnr/ppp1p1pp/8/3pPp2/8/8/PPPP1PPP/RNBQKBNR w KQkq f6 0 3",
    "1n2k3/P7/8/8/8/8/8/4K3 w - - 0 1",
    "4k3/8/8/8/8/8/8/R3K2R w KQ - 0 1",
    "r1bqkb1r/pppp1ppp/2n2n2/4p2Q/2B1P3/8/PPPP1PPP/RNB1K1NR w KQkq - 4 4",
    "5rk1/8/8/8/8/8/8/R4RK1 w - - 0 1",
    "4k3/8/8/8/8/8/8/N1N1K1N1 w - - 0 1",
]

if __name__ == "__main__":
    with open("tests/san_oracle.inc", "w") as out:
        out.write("/* san_oracle.inc — generated by tools/gen_san_oracle.py from python-chess: { fen, uci, san }. */\n")
        for fen in FENS:
            board = chess.Board(fen)
            for m in board.legal_moves:
                out.write('    { "%s", "%s", "%s" },\n' % (fen, m.uci(), board.san(m)))
